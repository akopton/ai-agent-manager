export type ConversationHistoryEntry = {
  id: string;
  sequence: number;
  role: 'user' | 'assistant';
  content: string;
};

/** What a turn sent, recorded with the turn (`context_manifest_json`). */
export type ConversationContextManifest = {
  version: 1;
  languageMode: ConversationLanguageMode;
  /** Sequences of the history messages included, oldest first. */
  includedSequences: number[];
  /** Earlier chat messages left out because of the history budget. */
  omittedMessages: number;
  historyCharacters: number;
  messageCharacters: number;
  /** Unreferenced notes left out of this prompt. */
  notesExcluded: number;
};

export type ComposedConversationPrompt = { prompt: string; manifest: ConversationContextManifest };

// The prompt is plain text in tagged sections. Closing tags inside conversation text are
// neutralized so the operator's or a model's text cannot end its own section early. This keeps the
// structure readable; it is not a security boundary.
const sectionTags = [
  'instructions',
  'language',
  'conversation_history',
  'message',
  'new_message',
  'explicit_references',
];
const sectionClosing = new RegExp(`</(${sectionTags.join('|')})>`, 'gi');

const neutralize = (text: string): string => text.replace(sectionClosing, '<\\/$1>');

/**
 * The newest history entries that fit into `budget` characters, in history order, and how many
 * older entries were left out. Shared by chat turns and task proposal generation (C3).
 */
export const selectConversationHistory = (
  history: readonly ConversationHistoryEntry[],
  budget: number,
): { included: ConversationHistoryEntry[]; omitted: number; characters: number } => {
  const included: ConversationHistoryEntry[] = [];
  let used = 0;
  for (let index = history.length - 1; index >= 0; index -= 1) {
    const entry = history[index];
    if (entry === undefined || used + entry.content.length > budget) {
      break;
    }
    included.unshift(entry);
    used += entry.content.length;
  }
  return { included, omitted: history.length - included.length, characters: used };
};

/**
 * Composes the stdin prompt of a turn: application instructions, the language instruction, earlier
 * **completed** chat exchanges (newest first until `historyBudget` characters; older ones are
 * omitted and counted), then explicit references and the new message. Unreferenced notes are excluded. Deterministic and pure.
 */
export const composeConversationPrompt = ({
  runtime,
  languageMode,
  history,
  message,
  notesExcluded = 0,
  historyBudget = conversationHistoryBudget,
  references = [],
}: {
  runtime: AgentRuntime;
  languageMode: ConversationLanguageMode;
  /** Earlier chat messages in history order; must not contain the new message. */
  history: readonly ConversationHistoryEntry[];
  message: string;
  notesExcluded?: number;
  historyBudget?: number;
  references?: readonly ConversationReferenceSnapshot[];
}): ComposedConversationPrompt => {
  const { included, omitted, characters: used } = selectConversationHistory(history, historyBudget);
  const historySection =
    included.length === 0
      ? omitted === 0
        ? 'This is the first message of the conversation.'
        : `${omitted} earlier messages were omitted to fit the context budget.`
      : [
          ...(omitted === 0 ? [] : [`${omitted} earlier messages were omitted to fit the budget.`]),
          ...included.map(
            (entry) => `<message role="${entry.role}">\n${neutralize(entry.content)}\n</message>`,
          ),
        ].join('\n');
  const prompt = [
    `<instructions>\n${[`You are running as ${runtimeNames[runtime]}.`, ...roleInstructions].join('\n')}\n</instructions>`,
    `<language>\n${conversationLanguageInstructions[languageMode]}\n</language>`,
    `<conversation_history>\n${historySection}\n</conversation_history>`,
    ...(references.length === 0 ? [] : [renderConversationReferences(references)]),
    `<new_message role="user">\n${neutralize(message)}\n</new_message>`,
  ].join('\n\n');
  return {
    prompt,
    manifest: {
      version: 1,
      languageMode,
      includedSequences: included.map((entry) => entry.sequence),
      omittedMessages: omitted,
      historyCharacters: used,
      messageCharacters: message.length,
      notesExcluded,
    },
  };
};

