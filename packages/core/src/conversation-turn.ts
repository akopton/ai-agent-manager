/** Persisted operator consent for AI Conversations. Separate from Trusted Local execution. */
export type ConversationConsent = {
  enabled: boolean;
  disclosureVersion: string | null;
  /** Unix milliseconds. */
  acceptedAt: number | null;
};

export type ConversationConsentDecision =
  | { ok: true }
  | { ok: false; code: 'conversation_ai_disabled' | 'conversation_ai_stale'; message: string };

/**
 * Whether AI replies may be requested, from persisted operator state only. Execution Mode
 * acceptance and project trust play no part.
 */
export const evaluateConversationConsent = (
  consent: ConversationConsent,
): ConversationConsentDecision => {
  if (!consent.enabled || consent.disclosureVersion === null || consent.acceptedAt === null) {
    return {
      ok: false,
      code: 'conversation_ai_disabled',
      message:
        'AI replies are off. Read and accept the AI Conversations disclosure in Settings to enable them.',
    };
  }
  if (consent.disclosureVersion !== conversationDisclosure.version) {
    return {
      ok: false,
      code: 'conversation_ai_stale',
      message:
        'The AI Conversations disclosure changed. Read and accept it again in Settings to enable AI replies.',
    };
  }
  return { ok: true };
};

