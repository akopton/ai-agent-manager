// C2 — CLI-backed conversation turns (`ARCHITECTURE.md` §15.6). A turn is one request for an AI
// reply to one user chat message. The web process stores the user message and a `queued` turn in
// one transaction; the worker claims it, runs the CLI and finishes it. Only a completed turn adds
// an assistant message: a failed, cancelled or interrupted turn never produces a reply.

/**
 * - `queued`: stored, waiting for the worker.
 * - `running`: claimed by a worker; the CLI is being prepared or runs.
 * - `stopping`: the operator asked to stop it; the worker is terminating the CLI.
 * - `completed`: the CLI reported success and the reply was stored.
 * - `failed`: refused before launch, or the CLI failed, timed out or produced no reply.
 * - `cancelled`: stopped by the operator (before or during the CLI run).
 * - `interrupted`: the worker stopped or restarted while the turn was active. Never retried
 *   automatically.
 */
export const conversationTurnStatuses = [
  'queued',
  'running',
  'stopping',
  'completed',
  'failed',
  'cancelled',
  'interrupted',
] as const;

export const conversationTurnStatusSchema = z.enum(conversationTurnStatuses);

export type ConversationTurnStatus = z.infer<typeof conversationTurnStatusSchema>;

export const activeConversationTurnStatuses = [
  'queued',
  'running',
  'stopping',
] as const satisfies readonly ConversationTurnStatus[];

export const isActiveConversationTurnStatus = (status: ConversationTurnStatus): boolean =>
  (activeConversationTurnStatuses as readonly ConversationTurnStatus[]).includes(status);

/** Turns that may be retried (as a new turn for the same message). */
