const authenticationPattern =
  /not logged in|please run \/login|\blog ?in\b|authenticat|unauthori[sz]ed|\b401\b|invalid api key|missing bearer|expired (?:token|session|credentials)/i;

/** Heuristic: whether a CLI failure message says the CLI is not signed in or the login expired. */
export const isCliAuthenticationFailure = (message: string): boolean =>
  authenticationPattern.test(message);

