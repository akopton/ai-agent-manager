/**
 * - `draft`: suggested by the AI, editable by the operator; nothing has been created.
 * - `approved`: the operator approved it; exactly one `Backlog` task was created. Final.
 * - `rejected`: dismissed by the operator. It can be reopened as a draft, never approved directly.
 */
export const taskProposalStatuses = ['draft', 'approved', 'rejected'] as const;

export const taskProposalStatusSchema = z.enum(taskProposalStatuses);

export type TaskProposalStatus = z.infer<typeof taskProposalStatusSchema>;

export const taskProposalStatusLabels: Readonly<Record<TaskProposalStatus, string>> = {
  draft: 'Draft',
  approved: 'Approved',
  rejected: 'Rejected',
};

/**
 * Operator edit of a draft. `revision` is the proposal revision the operator edited; a stale one
 * is refused instead of overwriting newer edits. The same field rules as tasks apply (`SPEC.md`
 * §5): switching the runtime without choosing a model resets the model to `Default`.
 */
export const updateTaskProposalInputSchema = z
  .strictObject({
    revision: z.number().int().min(1),
    title: taskTitleSchema.optional(),
    prompt: taskPromptSchema.optional(),
    agentRuntime: agentRuntimeSchema.optional(),
    modelId: modelSelectionSchema.optional(),
    priority: taskPrioritySchema.optional(),
    baseBranch: taskBaseBranchSchema.optional(),
  })
  .refine(
    (value) =>
      [
        value.title,
        value.prompt,
        value.agentRuntime,
        value.modelId,
        value.priority,
        value.baseBranch,
      ].some((field) => field !== undefined),
    { message: 'Change at least one field.' },
  );

export type UpdateTaskProposalInput = z.input<typeof updateTaskProposalInputSchema>;

export type UpdateTaskProposalData = z.output<typeof updateTaskProposalInputSchema>;

/** Approve, reject and reopen name the revision the operator saw. */
export const taskProposalActionInputSchema = z.strictObject({
  revision: z.number().int().min(1),
});

export type TaskProposalActionInput = z.input<typeof taskProposalActionInputSchema>;

/** Same rule as tasks and conversations: a runtime switch without a model resets it. */
export const resolveTaskProposalUpdate = (
  current: { agentRuntime: AgentRuntime },
  update: UpdateTaskProposalData,
): UpdateTaskProposalData => {
  const runtimeChanged =
    update.agentRuntime !== undefined && update.agentRuntime !== current.agentRuntime;
  if (runtimeChanged && update.modelId === undefined) {
    return { ...update, modelId: null };
  }
  return update;
};

// ---------------------------------------------------------------------------------------------
// Structured output contract
// ---------------------------------------------------------------------------------------------

/** One proposal as the AI must write it. Unknown keys are ignored, never stored. */
const outputProposalSchema = z.object({
  title: taskTitleSchema,
  prompt: taskPromptSchema,
  priority: z
    .string()
    .trim()
    .toLowerCase()
    .pipe(taskPrioritySchema)
    .optional()
    .default(taskPriorityDefault),
  rationale: optionalText(taskProposalNoteMaxLength, 'Rationale').optional().default(''),
  dependencies: optionalText(taskProposalNoteMaxLength, 'Dependencies').optional().default(''),
});

/** The proposal document. Each proposal item is validated separately (see below). */
const outputDocumentSchema = z.object({
  proposals: z.array(z.unknown()),
  note: optionalText(taskProposalNoteMaxLength, 'Note').optional().default(''),
});

/** A validated proposal from the AI: the suggested values, before any operator edit. */
export type ParsedTaskProposal = {
  title: string;
  prompt: string;
  priority: TaskPriority;
  /** Empty when the AI gave none. */
  rationale: string;
  dependencies: string;
};

export type SkippedTaskProposal = { index: number; reason: string };

export type TaskProposalOutput =
  | {
      ok: true;
      proposals: ParsedTaskProposal[];
      /** Items that failed validation or exceeded the per-generation limit; never stored. */
      skipped: SkippedTaskProposal[];
      /** The AI's note, for example why it proposed nothing. */
      note: string;
    }
  | { ok: false; message: string };

const fencePattern = /```[A-Za-z]*[ \t]*\n([\s\S]*?)\n?```/g;

/**
 * Finds the single JSON document of a reply: the whole reply, or the content of the only fenced
 * code block. Prose around a single block is tolerated; two or more blocks are ambiguous.
 */
export const extractSingleJsonDocument = (
  reply: string,
): { ok: true; json: string } | { ok: false } => {
  const trimmed = reply.trim();
  // A reply that starts as a document is parsed whole, so a truncated one reports invalid JSON.
  if (trimmed.startsWith('{')) {
    return { ok: true, json: trimmed };
  }
  const blocks = [...trimmed.matchAll(fencePattern)].map((match) => (match[1] ?? '').trim());
  const candidates = blocks.filter((block) => block.startsWith('{'));
  if (candidates.length === 1 && candidates[0] !== undefined) {
    return { ok: true, json: candidates[0] };
  }
  return { ok: false };
};

const describeIssue = (error: z.ZodError): string => {
  const issue = error.issues[0];
  if (issue === undefined) return 'invalid item';
  const path = issue.path.join('.');
  return path === '' ? issue.message : `${path}: ${issue.message}`;
};

/**
 * Validates a generation reply against the structured-output contract. The document must be one
 * JSON object with a `proposals` array; a reply that is not (truncated, prose only, several
 * documents) fails as a whole and nothing is stored. Inside a valid document, each item is
 * validated on its own: invalid items and items beyond `taskProposalMaxPerGeneration` are skipped
 * and reported, valid ones are kept in order. Never executes or interprets the content.
 */
export const parseTaskProposalOutput = (reply: string): TaskProposalOutput => {
  const document = extractSingleJsonDocument(reply);
  if (!document.ok) {
    return {
      ok: false,
      message:
        'The reply was not a single JSON proposal document, so no proposals were stored. Retry, or ask in the conversation for clearer, concrete tasks first.',
    };
  }
  let json: unknown;
  try {
    json = JSON.parse(document.json);
  } catch {
    return {
      ok: false,
      message:
        'The proposal document was not valid JSON (it may be incomplete), so no proposals were stored. Retry the generation.',
    };
  }
  const parsed = outputDocumentSchema.safeParse(json);
  if (!parsed.success) {
    return {
      ok: false,
      message: `The proposal document did not match the expected format (${describeIssue(parsed.error)}), so no proposals were stored. Retry the generation.`,
    };
  }
  const proposals: ParsedTaskProposal[] = [];
  const skipped: SkippedTaskProposal[] = [];
  parsed.data.proposals.forEach((item, index) => {
    const result = outputProposalSchema.safeParse(item);
    if (!result.success) {
      skipped.push({ index, reason: describeIssue(result.error) });
      return;
    }
    if (proposals.length >= taskProposalMaxPerGeneration) {
      skipped.push({
        index,
        reason: `more than ${taskProposalMaxPerGeneration} proposals in one generation`,
      });
      return;
    }
    proposals.push(result.data);
  });
  return { ok: true, proposals, skipped, note: parsed.data.note };
};

