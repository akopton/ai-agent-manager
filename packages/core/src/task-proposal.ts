// C3 — AI task proposals (`SPEC.md` §18.8, `ARCHITECTURE.md` §15.8). The operator explicitly asks
// a conversation for task proposals. The worker runs a **proposal generation** through the same
// conversation gate and launch boundary as a C2 chat turn, with a fixed structured-output contract
// (one JSON object). The reply is validated here; valid items become `draft` proposals, which the
// operator edits, rejects or approves one by one. Only an operator's approval creates a task, and
// that task always starts in `Backlog`. Nothing in this module runs a process or touches a task.

export const taskProposalIdSchema = z.uuid();

export const taskProposalGenerationIdSchema = z.uuid();

