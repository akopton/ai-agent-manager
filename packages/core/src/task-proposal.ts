// Generation lifecycle (same states as a chat turn)
// ---------------------------------------------------------------------------------------------

/**
 * A proposal generation uses the turn lifecycle of C2: `queued → running → completed | failed |
 * cancelled | interrupted`, plus `running → stopping → cancelled`. `completed` means the CLI
 * replied with a valid proposal document (which may contain no proposals).
 */
export const taskProposalGenerationStatuses = conversationTurnStatuses;

export type TaskProposalGenerationStatus = ConversationTurnStatus;

export const taskProposalGenerationStatusLabels: Readonly<
  Record<TaskProposalGenerationStatus, string>
> = {
  queued: 'Waiting',
  running: 'Generating',
  stopping: 'Stopping',
  completed: 'Generated',
  failed: 'Failed',
  cancelled: 'Stopped',
  interrupted: 'Interrupted',
};

/** Stored failure codes of a generation: those of a chat turn, plus an invalid document. */
export const taskProposalGenerationErrorCodes = [
  ...conversationTurnErrorCodes,
  /** The reply was not one valid proposal document; nothing was stored. */
  'malformed_output',
] as const;

export type TaskProposalGenerationErrorCode = (typeof taskProposalGenerationErrorCodes)[number];

/** Upper bound of proposals kept from one generation; further items are skipped and counted. */
export const taskProposalMaxPerGeneration = 12;

/** Maximum length of the operator's optional focus for a generation. */
export const taskProposalInstructionsMaxLength = 2_000;

/** Maximum length of the AI's rationale, dependency guidance and note. */
export const taskProposalNoteMaxLength = 2_000;

const optionalText = (max: number, label: string) =>
  z
    .string()
    .transform((value) => value.replace(/\r\n?/g, '\n').trim())
    .pipe(
      z
        .string()
        .max(max, `${label}: use at most ${max.toLocaleString('en')} characters.`)
        .refine((value) => !value.includes('\0'), { message: `${label} must not contain NUL.` }),
    );

/**
 * The operator's explicit request for task proposals from one completed AI reply (C3.1).
 * `sourceMessageId` names that reply; the server loads its text itself and never accepts content
 * from the browser. `requestId` is generated by the client per click and deduplicates double
 * submissions; `instructions` is an optional focus that narrows which tasks to extract.
 */
export const requestTaskProposalsInputSchema = z.strictObject({
  requestId: z.uuid(),
  sourceMessageId: z.uuid(),
  instructions: optionalText(taskProposalInstructionsMaxLength, 'Instructions').default(''),
});

export type RequestTaskProposalsInput = z.input<typeof requestTaskProposalsInputSchema>;

export const retryTaskProposalGenerationInputSchema = z.strictObject({ requestId: z.uuid() });

export type RetryTaskProposalGenerationInput = z.input<
  typeof retryTaskProposalGenerationInputSchema
>;

