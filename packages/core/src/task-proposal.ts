const proposalSectionClosing = new RegExp(`</(${proposalSectionTags.join('|')})>`, 'gi');

const neutralize = (text: string): string => text.replace(proposalSectionClosing, '<\\/$1>');

/** What a generation sent, recorded with it (`context_manifest_json`). Never the prompt. */
export type TaskProposalContextManifest = {
  version: 1;
  purpose: 'task_proposals';
  /**
   * `source_message` (C3.1): only one AI reply was sent. Absent in C3 manifests, which sent the
   * answered history up to `basedOnSequence`.
   */
  scope?: 'source_message';
  sourceMessageId?: string;
  sourceCharacters?: number;
  /** C4: repository references of a project-aware source reply that were named (no content). */
  sourceReferenceCount?: number;
  languageMode: ConversationLanguageMode;
  /** Highest message sequence the generation was based on. */
  basedOnSequence: number;
  includedSequences: number[];
  omittedMessages: number;
  historyCharacters: number;
  instructionsCharacters: number;
  notesExcluded: number;
};

/**
 * Composes the stdin prompt of a proposal generation: fixed instructions, the proposal language
 * rule, the output contract, earlier **completed** chat exchanges (newest first within the C2
 * budget; notes never included), then the developer's optional focus. Deterministic and pure.
 */
export const composeTaskProposalPrompt = ({
  runtime,
  languageMode,
  history,
  instructions,
  basedOnSequence,
  notesExcluded = 0,
  historyBudget = conversationHistoryBudget,
}: {
  runtime: AgentRuntime;
  languageMode: ConversationLanguageMode;
  history: readonly ConversationHistoryEntry[];
  instructions: string;
  basedOnSequence: number;
  notesExcluded?: number;
  historyBudget?: number;
}): { prompt: string; manifest: TaskProposalContextManifest } => {
  const { included, omitted, characters } = selectConversationHistory(history, historyBudget);
  const historySection = [
    ...(omitted === 0 ? [] : [`${omitted} earlier messages were omitted to fit the budget.`]),
    ...included.map(
      (entry) => `<message role="${entry.role}">\n${neutralize(entry.content)}\n</message>`,
    ),
  ].join('\n');
  const request =
    instructions === ''
      ? 'Propose tasks for the work discussed in this conversation.'
      : neutralize(instructions);
  const prompt = [
    `<instructions>\n${[`You are running as ${runtimeNames[runtime]}.`, ...proposalInstructions].join('\n')}\n</instructions>`,
    `<language>\n${taskProposalLanguageInstructions[languageMode]}\n</language>`,
    `<output_contract>\n${outputContract()}\n</output_contract>`,
    `<conversation_history>\n${historySection}\n</conversation_history>`,
    `<developer_request>\n${request}\n</developer_request>`,
  ].join('\n\n');
  return {
    prompt,
    manifest: {
      version: 1,
      purpose: 'task_proposals',
      languageMode,
      basedOnSequence,
      includedSequences: included.map((entry) => entry.sequence),
      omittedMessages: omitted,
      historyCharacters: characters,
      instructionsCharacters: instructions.length,
      notesExcluded,
    },
  };
};

